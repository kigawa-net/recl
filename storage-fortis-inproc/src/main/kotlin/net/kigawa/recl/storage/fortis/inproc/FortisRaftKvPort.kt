import net.kigawa.recl.storage.fortis.FortisScanResult
import net.kigawa.recl.storage.fortis.FortisSubmitResult
import java.util.concurrent.locks.ReentrantReadWriteLock
import kotlin.concurrent.read
import kotlin.concurrent.write
import kotlin.time.Duration

/** In-process, single-node only. This adapter does not implement the network KV API. */
internal class FortisRaftKvPort(
    private val runtime: RaftRuntime,
    machine: StorageEngineStateMachine,
    private val batches: ConditionalBatchClient,
    private val scans: RevisionScanClient,
    private val timeout: Duration,
) : FortisKvPort {
    private val calls = ReentrantReadWriteLock(true)
    private var acceptingCalls = true

    init {
        require(runtime.currentNode.stateMachine === machine)
        require(timeout.isPositive() && timeout.isFinite())
    }

    override fun getLinearizable(key: String): FortisRead = call({ FortisRead.Unavailable }) {
        val value = runtime.linearizableRead(timeout) {
            (it as StorageEngineStateMachine).getWithRevision(key.toByteArray(Charsets.UTF_8))
        }
        if (value == null) FortisRead.Absent else FortisRead.Value(value.value, value.revision)
    }

    override fun submit(batch: FortisConditionalBatch): FortisSubmitResult = call({ FortisSubmitResult.OutcomeUnknown }) {
        when (val response = batches.submit(batch.toRequest())) {
            is ConditionalBatchResponse.Stored -> FortisSubmitResult.Stored(response.receipt.toPortReceipt())
            ConditionalBatchResponse.DigestMismatch -> FortisSubmitResult.DigestMismatch
            ConditionalBatchResponse.OutcomeUnknown -> FortisSubmitResult.OutcomeUnknown
        }
    }

    override fun lookup(batch: FortisConditionalBatch): FortisLookupResult = call({ FortisLookupResult.Unavailable(it) }) {
        val request = batch.toRequest()
        // requestDigest is generated by ConditionalBatchCodec when Fortis constructs the request.
        when (val result = batches.lookupResult(request.principal, request.requestId, request.requestDigest)) {
            is RequestResultLookup.Found -> FortisLookupResult.Found(result.receipt.toPortReceipt())
            RequestResultLookup.DigestMismatch -> FortisLookupResult.DigestMismatch
            RequestResultLookup.ReceiptExpiredOrUnknown -> FortisLookupResult.ReceiptExpiredOrUnknown
        }
    }

    override fun scanPrefix(prefix: String, pageSize: Int, readRevision: Long?, cursor: ByteArray?): FortisScanResult =
        call({ FortisScanResult.Unavailable(it) }) {
            val request = ScanRequest(prefix.toByteArray(Charsets.UTF_8), readRevision, cursor?.let(::OpaqueCursor), pageSize)
            when (val result = scans.scanAtRevision(request)) {
                is ScanResult.Page -> FortisScanResult.Page(
                    result.entries.map { FortisScanEntry(it.key.toString(Charsets.UTF_8), it.value, it.revision) },
                    result.revision,
                    result.nextCursor?.toBytes(),
                )
                is ScanResult.RevisionCompacted -> FortisScanResult.RevisionCompacted(result.floor)
                is ScanResult.InvalidCursor -> FortisScanResult.InvalidCursor(result.reason)
                is ScanResult.Unavailable -> FortisScanResult.Unavailable(result.reason)
                is ScanResult.Unsupported -> FortisScanResult.Unsupported(result.reason)
                is ScanResult.RevisionUnavailable -> FortisScanResult.Unavailable(
                    "revision ${result.revision} is ahead of applied revision ${result.latest}",
                )
            }
        }

    fun stopAcceptingCalls() = calls.write {
        acceptingCalls = false
    }

    private fun <T> call(unavailable: (String) -> T, operation: suspend () -> T): T = calls.read {
        if (!acceptingCalls) return@read unavailable("STOPPED")
        try {
            runBlocking { withTimeout(timeout) { operation() } }
        } catch (_: TimeoutCancellationException) {
            unavailable("TIMEOUT")
        } catch (_: RaftReadNotLeaderException) {
            unavailable("NOT_LEADER")
        } catch (_: RaftReadLeadershipLostException) {
            unavailable("LEADERSHIP_LOST")
        } catch (_: RaftReadStoppedException) {
            unavailable("STOPPED")
        }
    }

    private fun FortisConditionalBatch.toRequest() = ConditionalBatchRequest(
        principal,
        requestId,
        conditions.map { condition ->
            val key = condition.key.toByteArray(Charsets.UTF_8)
            when (condition) {
                is FortisCondition.Absent -> KvCondition.Absent(key)
                is FortisCondition.RevisionEquals -> KvCondition.RevisionEquals(key, condition.revision)
            }
        },
        mutations.map { mutation ->
            when (mutation) {
                is FortisMutation.Put -> KvMutation.Put(mutation.key.toByteArray(Charsets.UTF_8), mutation.value)
            }
        },
    )

    private fun RequestReceipt.toPortReceipt(): FortisReceipt = when (val result = outcome) {
        is BatchOutcome.Applied -> FortisReceipt(result.raftIndex, FortisOutcome.Applied)
        is BatchOutcome.Rejected -> FortisReceipt(
            result.raftIndex,
            FortisOutcome.Rejected(result.failedCondition, result.observedRevision),
        )
    }
}
